CREATE OR REPLACE FUNCTION XOR24 (p_str VARCHAR2)
  RETURN VARCHAR2
IS

  -- double size of possible input string
  xor_arg       VARCHAR2 (8000) := '';
  counter       NUMBER          := 0;
  arg_length    NUMBER;
  arg_lengthb   NUMBER;
BEGIN
  arg_length := LENGTH (p_str);
  arg_lengthb := LENGTHB (p_str);

  IF (arg_length != arg_lengthb)
  THEN
    raise_application_error (-20001
                            ,    'Invalid argument. The argument '
                              || p_str
                              || ' contains invalid character(s). '
                              || 'Only ascii/1-byte characters are allowed'
                            );
  END IF;

  /*
    Oracle does only support bitwise XOR, not XOR.
    Therefore the xor_arg is filled with 0x18 (24)
    corresponding to each character in the p_str argument
  */
  WHILE (counter < arg_length)
  LOOP
    xor_arg := xor_arg || '18';
    counter := counter + 1;
  END LOOP;

  RETURN UTL_RAW.cast_to_varchar2(UTL_RAW.bit_xor (UTL_RAW.cast_to_raw (p_str),xor_arg));
END;
/


